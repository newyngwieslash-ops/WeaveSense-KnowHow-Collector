#!/usr/bin/env bash
# Clean TEST stack only. Runs the checked-in application containers, never pushes.
set -euo pipefail
cd "$(dirname "$0")/../.."
test "${VIDEO_FULLSTACK_TEST_ACK:-}" = DISPOSABLE_TEST_ONLY || { echo 'Disposable TEST acknowledgement required'; exit 2; }
test ! -e .env.flow || { echo 'Refusing to overwrite existing .env.flow'; exit 2; }
test ! -e .local/video-fullstack || { echo 'Refusing to reuse prior private TEST state'; exit 2; }
command -v docker >/dev/null
docker compose version
export COMPOSE_PROJECT_NAME="knowhow-ci-${GITHUB_RUN_ID:-$(date +%s)}-${GITHUB_RUN_ATTEMPT:-1}"
[[ "$COMPOSE_PROJECT_NAME" =~ ^knowhow-ci-[0-9]+-[0-9]+$ ]] || { echo 'Invalid disposable TEST project identity'; exit 2; }
export VIDEO_FULLSTACK_BASE_URL=http://127.0.0.1:4180
export VIDEO_FULLSTACK_STATE="$PWD/.local/video-fullstack/state.json"
export VIDEO_FULLSTACK_RESULT="$PWD/.local/video-fullstack/result.json"
export VIDEO_FULLSTACK_SOURCE_SHA="$(git rev-parse HEAD)"
out="${VIDEO_FULLSTACK_EVIDENCE:?set an evidence output directory}"
mkdir -p "$out"
out="$(cd "$out" && pwd)"
private="$PWD/.local/video-fullstack"
compose=(docker compose --project-name "$COMPOSE_PROJECT_NAME" --env-file .env.flow -f docker-compose.flow.yml -f docker-compose.video.yml -f scripts/fullstack/compose.test.yml --profile core --profile video)
created=false
journal_created=false
journal="${COMPOSE_PROJECT_NAME}-journal"
test -z "$(docker ps -aq --filter "label=com.docker.compose.project=$COMPOSE_PROJECT_NAME")" || { echo 'Refusing existing TEST project containers'; exit 2; }
test -z "$(docker volume ls -q --filter "label=com.docker.compose.project=$COMPOSE_PROJECT_NAME")" || { echo 'Refusing existing TEST project volumes'; exit 2; }
if docker volume inspect "$journal" >/dev/null 2>&1; then echo 'Refusing existing external journal'; exit 2; fi
cleanup() {
  status=$?
  trap - EXIT
  set +e
  if $created; then
    # Retain completed assertions on browser failure too; this report contains
    # no login state and goes through the same fail-closed sanitizer below.
    if test -f "$VIDEO_FULLSTACK_RESULT"; then cp "$VIDEO_FULLSTACK_RESULT" "$out/browser-last-observation.json"; fi
    "${compose[@]}" logs --no-color 2>&1 | python scripts/fullstack/sanitize.py > "$out/service-logs.txt" || true
    "${compose[@]}" ps --all --format json | python scripts/fullstack/sanitize.py > "$out/containers.jsonl" || true
    down_status=0; journal_status=0; containers_status=0; volumes_status=0; journal_query_status=0
    "${compose[@]}" down --volumes --remove-orphans --timeout 30 > "$out/cleanup-runtime.txt" 2>&1 || down_status=$?
    if $journal_created; then docker volume rm "$journal" >> "$out/cleanup-runtime.txt" 2>&1 || journal_status=$?; fi
    remaining_containers="$(docker ps -aq --filter "label=com.docker.compose.project=$COMPOSE_PROJECT_NAME" 2>> "$out/cleanup-runtime.txt")" || containers_status=$?
    remaining_volumes="$(docker volume ls -q --filter "label=com.docker.compose.project=$COMPOSE_PROJECT_NAME" 2>> "$out/cleanup-runtime.txt")" || volumes_status=$?
    remaining_journal="$(docker volume ls -q --filter "name=$journal" 2>> "$out/cleanup-runtime.txt")" || journal_query_status=$?
    # No broad deletion or retry: failed/ambiguous cleanup is a failed TEST run.
    if ! python - "$out" "$COMPOSE_PROJECT_NAME" "$down_status" "$journal_status" "$containers_status" "$volumes_status" "$journal_query_status" "$remaining_containers" "$remaining_volumes" "$remaining_journal" <<'PY'
import json, pathlib, sys
root, project = pathlib.Path(sys.argv[1]), sys.argv[2]
statuses = dict(zip(['compose_down', 'owned_journal_remove', 'containers_query', 'volumes_query', 'journal_query'], map(int, sys.argv[3:8])))
remaining = dict(zip(['containers', 'project_volumes', 'exact_journal'], [value.splitlines() for value in sys.argv[8:11]]))
# Docker's name filter can match substrings; only this exact owned name matters.
remaining['exact_journal'] = [name for name in remaining['exact_journal'] if name == project + '-journal']
verified = all(code == 0 for code in statuses.values()) and not any(remaining.values())
(root / 'cleanup-verification.json').write_text(json.dumps({'compose_project': project, 'exit_statuses': statuses, 'remaining_owned_resources': remaining, 'verified': verified}) + '\n')
sys.exit(0 if verified else 1)
PY
    then status=1; fi
    if python scripts/fullstack/sanitize.py --artifacts "$out" .github/browser/test-results; then
      if test -n "${GITHUB_OUTPUT:-}"; then echo 'sanitized=true' >> "$GITHUB_OUTPUT"; fi
    else
      echo 'Artifact sanitization failed: upload is disabled' >&2
      status=1
    fi
    # Only files generated by this run, never an operator's pre-existing env.
    if ! rm -f .env.flow "$private/state.json"; then status=1; fi
    if test -e .env.flow || test -e "$private/state.json"; then status=1; fi
  fi
  printf '{"exit_code":%s,"compose_project":"%s","production_ready":false,"synthetic_external_model":true,"real_platform_acquisition":false}\n' "$status" "$COMPOSE_PROJECT_NAME" > "$out/outcome.json"
  exit "$status"
}
trap cleanup EXIT
python scripts/fullstack/configure.py prepare
created=true
git rev-parse HEAD > "$out/source-commit.txt"
"${compose[@]}" config --quiet
docker volume create "$journal" >/dev/null
journal_created=true
"${compose[@]}" build platform web loom-engine video-worker provider-fixture 2>&1 | tee "$out/build.log"
"${compose[@]}" images --format json > "$out/images-before-start.json"
"${compose[@]}" run --rm --no-deps loom-engine node flow/video-journal-cli.ts init | python scripts/fullstack/configure.py journal
"${compose[@]}" up -d postgres redis minio
"${compose[@]}" run --rm minio-init
"${compose[@]}" up -d --wait --wait-timeout 180 platform web
node scripts/fullstack/readiness.mjs > "$out/auth-readiness-initial.json"
node .github/browser/fullstack-bootstrap.mjs > "$out/bootstrap.json"
platform_before="$("${compose[@]}" ps -q platform)"
web_before="$("${compose[@]}" ps -q web)"
python scripts/fullstack/configure.py scope
set -a
. ./.env.flow
set +a
# An independent account, limited to this one temporary tenant/workspace's video
# prefix; the Python decoder never receives MinIO root credentials.
"${compose[@]}" run --rm --no-deps \
  -e VIDEO_OBJECT_ACCESS_KEY -e VIDEO_OBJECT_SECRET_KEY \
  -v "$private/object-policy.json:/test/object-policy.json:ro" \
  --entrypoint /bin/sh minio-init -c '
    set -eu
    mc alias set flow http://minio:9000 "$MINIO_ROOT_USER" "$MINIO_ROOT_PASSWORD" >/dev/null
    mc admin user add flow "$VIDEO_OBJECT_ACCESS_KEY" "$VIDEO_OBJECT_SECRET_KEY" >/dev/null
    mc admin policy create flow fullstack-video /test/object-policy.json >/dev/null
    mc admin policy attach flow fullstack-video --user "$VIDEO_OBJECT_ACCESS_KEY" >/dev/null
  '
"${compose[@]}" up -d --wait --wait-timeout 240 platform web loom-engine loom-scheduler video-worker provider-fixture
curl --fail --silent --show-error --retry 30 --retry-delay 1 --retry-connrefused --max-time 3 "$VIDEO_FULLSTACK_BASE_URL/api/health/ready" > "$out/proxy-readiness.json"
node scripts/fullstack/readiness.mjs > "$out/auth-readiness-recreated.json"
platform_after="$("${compose[@]}" ps -q platform)"
web_after="$("${compose[@]}" ps -q web)"
test "$platform_before" != "$platform_after"
test "$web_before" = "$web_after"
"${compose[@]}" exec -T web nginx -v > "$out/nginx-runtime.txt" 2>&1
"${compose[@]}" exec -T web nginx -t >> "$out/nginx-runtime.txt" 2>&1
printf '{"backend_recreated":true,"web_not_recreated":true,"proxied_readiness_after_recreation":true}\n' > "$out/proxy-recreation.json"
"${compose[@]}" images --format json > "$out/images.json"
"${compose[@]}" ps --all --format json | python scripts/fullstack/sanitize.py > "$out/healthy-start.jsonl"
export FULLSTACK_TENANT_ID="$(node -e "console.log(JSON.parse(require('fs').readFileSync(process.env.VIDEO_FULLSTACK_STATE)).tenantId)")"
export FULLSTACK_WORKSPACE_ID="$(node -e "console.log(JSON.parse(require('fs').readFileSync(process.env.VIDEO_FULLSTACK_STATE)).workspaceId)")"
observe() {
  "${compose[@]}" exec -T -e FULLSTACK_TENANT_ID -e FULLSTACK_WORKSPACE_ID loom-engine node --input-type=module < scripts/fullstack/observe.mjs
}
(cd .github/browser && npx playwright test --config playwright.fullstack.config.mjs) 2>&1 | python scripts/fullstack/sanitize.py
cp "$VIDEO_FULLSTACK_RESULT" "$out/browser-initial.json"
node scripts/fullstack/long-input.mjs > "$out/long-input.json"
observe > "$out/persistence-before-restart.json"
# Browser process has exited. Restart real services with the same volumes.
"${compose[@]}" restart platform loom-engine loom-scheduler video-worker
"${compose[@]}" up -d --wait --wait-timeout 240 platform web loom-engine loom-scheduler video-worker provider-fixture
curl --fail --silent --show-error --retry 30 --retry-delay 1 --retry-connrefused --max-time 3 "$VIDEO_FULLSTACK_BASE_URL/api/health/ready" > "$out/proxy-readiness-after-restart.json"
node scripts/fullstack/readiness.mjs > "$out/auth-readiness-restarted.json"
(cd .github/browser && VIDEO_FULLSTACK_PHASE=restart npx playwright test --config playwright.fullstack.config.mjs) 2>&1 | python scripts/fullstack/sanitize.py
cp "$VIDEO_FULLSTACK_RESULT" "$out/browser-after-restart.json"
observe > "$out/persistence-after-restart.json"
python - "$out" <<'PY'
import json, pathlib, sys
from scripts.fullstack.skill_receipts import verify as verify_skill_receipts, verify_native_authority
root = pathlib.Path(sys.argv[1])
before = json.loads((root / 'persistence-before-restart.json').read_text())
after = json.loads((root / 'persistence-after-restart.json').read_text())
browser = json.loads((root / 'browser-after-restart.json').read_text())
skill_receipts = verify_skill_receipts(before, after, browser)
(root / 'skill-evaluation-verification.json').write_text(json.dumps(skill_receipts) + '\n')
native_authority = verify_native_authority(before, after, browser)
(root / 'native-source-authority-verification.json').write_text(json.dumps(native_authority) + '\n')
assert before['objects'] == after['objects'], 'Persisted object IDs/hashes changed across restart'
assert [x['id'] for x in before['jobs']] == [x['id'] for x in after['jobs']], 'Job identity changed across restart'
assert before['stable_identity_sha256'] == after['stable_identity_sha256'], 'Evidence/revision/release identity changed across restart'
(root / 'restart-verification.json').write_text(json.dumps({'same_job_ids': True, 'same_object_hashes': True, 'actual_service_restart': True}) + '\n')
PY
echo 'Actual TEST stack + authenticated browser + persistence/restart checks passed; not business release acceptance.'
